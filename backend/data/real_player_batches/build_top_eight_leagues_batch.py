def player_entry(
    *,
    key: str,
    name: str,
    nationality: str,
    nationality_code: str,
    dob: str,
    position: str,
    secondary_positions: list[str],
    club: str,
    club_key: str,
    league: str,
    league_key: str,
    dominant_foot: str,
    height_cm: int,
    weight_kg: int,
    overall_rating: int,
    potential: int,
    market_value_eur: float,
    appearances: int,
    minutes: int,
    goals: int = 0,
    assists: int = 0,
    clean_sheets: int | None = None,
    aliases: list[str] | None = None,
) -> dict[str, object]:
    payload: dict[str, object] = {
        "source_name": "curated-feed",
        "source_player_key": key,
        "canonical_name": name,
        "known_aliases": aliases or [name],
        "nationality": nationality,
        "nationality_code": nationality_code,
        "date_of_birth": dob,
        "birth_year": int(dob[:4]),
        "dominant_foot": dominant_foot,
        "height_cm": height_cm,
        "weight_kg": weight_kg,
        "primary_position": position,
        "secondary_positions": secondary_positions,
        "current_real_world_club": club,
        "current_real_world_club_key": club_key,
        "current_real_world_league": league,
        "current_real_world_league_key": league_key,
        "competition_level": "elite",
        "overall_rating": overall_rating,
        "potential": potential,
        "current_market_reference_value": market_value_eur,
        "market_reference_currency": "EUR",
        "appearances": appearances,
        "minutes_played": minutes,
        "goals": goals,
        "assists": assists,
        "identity_confidence_score": 0.99,
        "is_verified_real_player": True,
    }
    if clean_sheets is not None:
        payload["clean_sheets"] = clean_sheets
    return payload


