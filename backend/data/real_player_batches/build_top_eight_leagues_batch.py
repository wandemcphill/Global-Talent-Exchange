def main() -> None:
    manifest = {
        "mode": "curated_seed",
        "ingestion_source_version": "top-eight-leagues-batch-v1",
        "as_of": "2026-11-01T20:00:00+00:00",
        "players": TOP_EIGHT_PLAYERS,
    }
    leagues_represented = sorted(list({p["current_real_world_league"] for p in TOP_EIGHT_PLAYERS}))
    clubs_represented = sorted(list({p["current_real_world_club"] for p in TOP_EIGHT_PLAYERS}))
    review = {
        "batch_id": "top-eight-leagues-batch-v1",
        "total_players": len(TOP_EIGHT_PLAYERS),
        "total_leagues": len(leagues_represented),
        "leagues": leagues_represented,
        "total_clubs": len(clubs_represented),
        "clubs": clubs_represented,
    }

    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    REVIEW_PATH.write_text(json.dumps(review, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(
        f"Generated {len(TOP_EIGHT_PLAYERS)} players across {len(leagues_represented)} top leagues in {MANIFEST_PATH}"
    )

    # Also update first_batch.json so running default run_real_player_batch includes Saka and top league players
    first_batch_data = json.loads(FIRST_BATCH_PATH.read_text(encoding="utf-8"))
    existing_keys = {p["source_player_key"] for p in first_batch_data["players"]}

    # Update Vinicius in first_batch if it had mojibake
    for p in first_batch_data["players"]:
        if p["source_player_key"] == "vinicius-001":
            p["canonical_name"] = "Vinícius Júnior"
            p["known_aliases"] = ["Vinicius Jr", "Vinicius Junior"]

    # Append Saka and top eight players that aren't already in first_batch
    added_to_first_batch = 0
    for p in TOP_EIGHT_PLAYERS:
        if p["source_player_key"] not in existing_keys:
            first_batch_data["players"].append(p)
            existing_keys.add(p["source_player_key"])
            added_to_first_batch += 1

    FIRST_BATCH_PATH.write_text(json.dumps(first_batch_data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Updated first_batch.json: added {added_to_first_batch} players (total: {len(first_batch_data['players'])})")


if __name__ == "__main__":
    main()
