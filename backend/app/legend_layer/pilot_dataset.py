from __future__ import annotations

from datetime import date
from typing import Literal

from pydantic import BaseModel, Field, field_validator


class LegendaryPlayerPilotRecord(BaseModel):
    provider_external_id: str = Field(description="Unique provider external ID for the legendary player")
    full_name: str = Field(description="Factual full historical name")
    canonical_display_name: str = Field(description="Display name widely known in football history")
    first_name: str | None = None
    last_name: str | None = None
    nationality: str = Field(description="Factual country name of national team representation")
    country_code: str = Field(description="Alpha-3 country code (e.g. BRA, ARG, NLD, DEU, FRA, CMR)")
    continent: Literal["Africa", "Europe", "South America", "Asia", "North America"]
    preferred_foot: Literal["left", "right"]
    primary_position: str = Field(description="Primary position (e.g. GK, CB, LB, CM, AM, ST, RW)")
    secondary_positions: list[str] = Field(default_factory=list)
    height_cm: int = Field(ge=140, le=220, description="Height in cm")
    weight_kg: int = Field(ge=50, le=120, description="Weight in kg")
    date_of_birth: date = Field(description="Factual date of birth")
    era: str = Field(description="Historical playing era (e.g. 1950s/1960s, 1980s, 2000s)")
    physical_profile: str = Field(description="Description of physical profile")
    role: str = Field(description="Tactical role in football history")
    fame_level: Literal["Global Superstar", "Continental Icon", "Cult Legend", "National Hero"]
    signature_traits: list[str] = Field(default_factory=list)
    portrait_asset_ref: str = Field(description="Portrait asset URI or reference token")
    portrait_source_provider: str = Field(default="gtex_legend_vault")
    is_active: bool = True
    is_tradable: bool = True
    is_rentable: bool = True
    market_value_eur: float = Field(ge=100_000.0, description="Base historical reference valuation EUR")

    @field_validator("full_name", "canonical_display_name", "nationality", "country_code", "primary_position")
    @classmethod
    def require_non_empty(cls, value: str) -> str:
        s = value.strip()
        if not s:
            raise ValueError("Field must not be empty or whitespace only")
        return s


