from __future__ import annotations

from fastapi import APIRouter, Depends, Request
from sqlalchemy.orm import Session

from app.auth.dependencies import get_optional_current_user, get_session
from app.models.base import utcnow
from app.models.user import User
from app.public_pulse.schemas import (
    LiveWorldPulseView,
    PublicTrafficHeartbeatCreate,
    PublicTrafficHeartbeatView,
)
from app.public_pulse.service import TRAFFIC_HEARTBEAT_INTERVAL_SECONDS, PublicPulseService

router = APIRouter(prefix="/public", tags=["public-pulse"])


@router.get("/live-stats", response_model=LiveWorldPulseView)
def get_live_world_pulse(session: Session = Depends(get_session)) -> LiveWorldPulseView:
    """Public homepage metrics: unique visits, active logins, clubs and live-match managers."""
    return PublicPulseService(session).live_world_pulse()


@router.post("/traffic/heartbeat", response_model=PublicTrafficHeartbeatView)
def record_public_traffic_heartbeat(
    payload: PublicTrafficHeartbeatCreate,
    request: Request,
    session: Session = Depends(get_session),
    current_user: User | None = Depends(get_optional_current_user),
) -> PublicTrafficHeartbeatView:
    """Record a page view and refresh the authenticated user's live-presence timestamp.

    Visitor identifiers are random first-party UUIDs generated by the browser. Only
    an HMAC digest is stored; raw identifiers, IP addresses and query strings are not.
    """
    auth_session = getattr(request.state, "auth_session", None)
    if auth_session is not None and current_user is not None:
        auth_session.last_used_at = utcnow()

    if payload.page_view:
        PublicPulseService(session).record_page_view(
            visitor_id=payload.visitor_id,
            path=payload.path,
            user_id=current_user.id if current_user is not None else None,
        )

    # Commit the heartbeat's last_used_at update even on interval-only heartbeats.
    if auth_session is not None or payload.page_view:
        session.commit()

    return PublicTrafficHeartbeatView(
        accepted=True,
        recorded_page_view=payload.page_view,
        heartbeat_interval_seconds=TRAFFIC_HEARTBEAT_INTERVAL_SECONDS,
    )


__all__ = ["router"]
