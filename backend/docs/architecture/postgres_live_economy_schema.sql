DECLARE
    partition_count integer := 32;
    partition_index integer;
BEGIN
    FOR partition_index IN 0..partition_count - 1 LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS match_events_p%s PARTITION OF match_events
             FOR VALUES WITH (MODULUS %s, REMAINDER %s)',
            lpad(partition_index::text, 2, '0'),
            partition_count,
            partition_index
        );
    END LOOP;
END $$;

