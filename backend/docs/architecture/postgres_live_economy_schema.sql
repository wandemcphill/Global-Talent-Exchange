CREATE TABLE IF NOT EXISTS matches (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    competition_id uuid REFERENCES competitions(id) ON DELETE SET NULL,
    host_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
    match_type text NOT NULL DEFAULT 'gtex_hosted'
        CHECK (match_type IN ('gtex_hosted', 'user_hosted', 'fast_match')),
    home_club_id uuid NOT NULL REFERENCES clubs(id) ON DELETE RESTRICT,
    away_club_id uuid NOT NULL REFERENCES clubs(id) ON DELETE RESTRICT,
    entry_fee_minor bigint NOT NULL DEFAULT 0 CHECK (entry_fee_minor >= 0),
    prize_pool_minor bigint NOT NULL DEFAULT 0 CHECK (prize_pool_minor >= 0),
    status text NOT NULL CHECK (status IN ('scheduled', 'live', 'completed', 'cancelled')),
    scheduled_at timestamptz NOT NULL,
    result jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (home_club_id <> away_club_id)
);

CREATE INDEX IF NOT EXISTS ix_matches_competition_scheduled_at
    ON matches (competition_id, scheduled_at DESC);
CREATE INDEX IF NOT EXISTS ix_matches_host_user_scheduled_at
    ON matches (host_user_id, scheduled_at DESC);
