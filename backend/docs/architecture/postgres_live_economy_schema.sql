CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email citext NOT NULL UNIQUE,
    username citext NOT NULL UNIQUE,
    password_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS wallets (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid REFERENCES users(id) ON DELETE CASCADE,
    code text NOT NULL UNIQUE,
    asset_code text NOT NULL CHECK (asset_code IN ('GTEX', 'FAN')),
    owner_scope text NOT NULL DEFAULT 'user'
        CHECK (owner_scope IN ('user', 'platform')),
    wallet_type text NOT NULL DEFAULT 'spendable'
        CHECK (wallet_type IN ('spendable', 'escrow', 'rewards_pool', 'lottery_pool')),
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'frozen', 'closed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (
        (owner_scope = 'user' AND user_id IS NOT NULL)
        OR (owner_scope = 'platform' AND user_id IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS ix_wallets_user_asset
    ON wallets (user_id, asset_code);

CREATE TABLE IF NOT EXISTS transactions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    transaction_type text NOT NULL CHECK (
        transaction_type IN (
            'deposit',
            'withdrawal',
            'match_entry_fee',
            'match_reward',
            'lottery_reward',
            'player_share_buy',
            'player_share_sell',
            'club_share_buy',
            'club_share_payout',
            'transfer_settlement',
            'adjustment'
        )
    ),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'committed', 'failed', 'cancelled')),
    reference_id text UNIQUE,
    external_reference text,
    initiated_by_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    committed_at timestamptz
);

CREATE INDEX IF NOT EXISTS ix_transactions_type_created_at
    ON transactions (transaction_type, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_transactions_status_created_at
    ON transactions (status, created_at DESC);

CREATE TABLE IF NOT EXISTS ledger_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id uuid NOT NULL REFERENCES transactions(id) ON DELETE RESTRICT,
    wallet_id uuid NOT NULL REFERENCES wallets(id) ON DELETE RESTRICT,
    entry_type text NOT NULL CHECK (entry_type IN ('available', 'locked')),
    direction text NOT NULL CHECK (direction IN ('debit', 'credit')),
    amount_minor bigint NOT NULL CHECK (amount_minor > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_ledger_entries_transaction_wallet
    ON ledger_entries (transaction_id, wallet_id);
CREATE INDEX IF NOT EXISTS ix_ledger_entries_wallet_created_at
    ON ledger_entries (wallet_id, created_at DESC);

CREATE TABLE IF NOT EXISTS ledger_balance_projections (
    wallet_id uuid PRIMARY KEY REFERENCES wallets(id) ON DELETE CASCADE,
    available_balance_minor bigint NOT NULL DEFAULT 0 CHECK (available_balance_minor >= 0),
    locked_balance_minor bigint NOT NULL DEFAULT 0 CHECK (locked_balance_minor >= 0),
    updated_at timestamptz NOT NULL DEFAULT now(),
